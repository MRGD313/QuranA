"""ساخت پرامپت گفت‌وگو با چت‌بات، همراه فایل گزارش قرآنی.

پرامپت باید:
- مخصوص همان ریشه و واژهٔ درخواست باشد؛
- کاربر را به وحدت معنایی خانوادهٔ ریشه و فهم «قرآن با قرآن» مقید کند؛
- فقط به فایل پیوست ارجاع دهد و از منبع بیرونی/حدس منع کند؛
- تحلیل عملی (چه می‌کنند/چه نمی‌کنند) و پیامدها را بخواهد.
"""
from config import QURAN_TEXT_SOURCE

MAX_PROMPT_CHARS = 4000  # سقف پیام بله ۴۰۹۶ نویسه است


def build_chat_prompt(root: str, input_word: str, normalized: str, result: dict) -> str:
    forms = result.get("distinct_word_forms", 0)
    events = result.get("lexical_events", 0)
    ayat = result.get("unique_ayahs", 0)
    normalized_hint = ""
    if normalized and normalized != input_word:
        normalized_hint = f" (صورت نرمال‌شده: «{normalized}»)"

    prompt = f"""تو یک پژوهشگر قرآن، زبان‌شناس عربی و مفسر هستی. فایل متنی پیوست، گزارش واژه‌های هم‌ریشهٔ ریشهٔ «{root}» در قرآن کریم است؛ واژهٔ ورودی «{input_word}»{normalized_hint} بوده است. این گزارش شامل {forms} واژهٔ قرآنی متمایز، {events} رخداد واژگانی و {ayat} آیهٔ یکتاست و متن کامل آیات را از منبع {QURAN_TEXT_SOURCE} و تحلیل صرفی را از Quranic Arabic Corpus دارد.

فقط بر پایهٔ همین فایل و متن آیات آن تحلیل کن. از جست‌وجوی اینترنتی، حافظه، منبع بیرونی یا تفسیر آماده استفاده نکن. اگر دادهٔ فایل برای یک ادعا کافی نیست، صریح بگو و آن را به‌عنوان فرض علامت بده. آیات را تغییر نده و هر ادعا را با ارجاع «سوره:آیه» به همان فایل مستند کن.

اصول تحلیل:
۱) واژه‌های هم‌ریشه در قرآن را دارای یک هستهٔ معنایی مشترک یا هم‌محور بدان. تا حد امکان یک معنای همگن و یکدست برای خانوادهٔ این ریشه پیشنهاد کن؛ به‌جای انباشتن معانی پراکنده، وجه اشتراک، تفاوت صور صرفی و تحول کاربرد را نشان بده.
۲) قرآن را با قرآن بفهم: همهٔ رخدادهای این ریشه را در فایل کنار هم بگذار و از سیاق، همنشین‌ها، تقابل‌ها، تعبیرهای تکرارشونده و تفاوت باب‌های فعل استفاده کن.
۳) بین ریشه، مدخل (lemma) و صورت‌های مشتق (اسم فاعل، مفعول، مصدر، صفت) تفکیک قائل شو، اما پیوند معنایی‌شان را حفظ کن.

تحلیل خواسته‌شده:
- پیکره: صورت‌های متمایز، نوع صرفی و پراکندگی رخدادها را خلاصه کن.
- معنای محوری: چه هستهٔ معنایی مشترکی این خانواده را به هم می‌پیوندد؟
- کاربرد قرآنی: این ریشه در قرآن در چه میدان‌های معنایی و در برابر چه مفاهیمی به کار رفته است؟
- مصداق عملی: به‌طور خاص «{input_word}» چه رفتاری را توصیف می‌کند؟ صاحبان این وصف چه می‌کنند و چه نمی‌کنند؟ ویژگی‌ها، انگیزه‌ها و بایسته‌هایشان را از آیات استخراج کن.
- پیامدها: چه پاداش‌ها، داوری‌ها یا پیامدهایی در آیات مرتبط با این ریشه ذکر شده است؟ رابطهٔ آن‌ها را با معنای ریشه توضیح بده (اگر در فایل آمده باشد، به مواردی مانند حکم و علم نیز توجه کن).
- جمع‌بندی: یک تعریف فشرده و منسجم از این ریشه و مشتقاتش ارائه بده، بدون تحمیل معانی بیرونی.

ساختار پاسخ: فارسی روان و بخش‌بندی‌شده؛ ابتدا خلاصه‌ای کوتاه، سپس تحلیل با ارجاع‌های دقیق. اگر جایی برداشت تو با تفسیرهای رایج متفاوت است، آن را با احتیاط علامت بده. در پایان سه پرسش پژوهشی برای ادامهٔ گفت‌وگو پیشنهاد کن."""
    return prompt[:MAX_PROMPT_CHARS]
